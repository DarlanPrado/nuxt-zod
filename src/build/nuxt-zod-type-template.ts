/**
 * Source for `addTypeTemplate({ filename: 'types/nuxt-zod.d.ts' })` in the module setup.
 * Keeps `module.ts` readable; version-specific bits are only `zodSpecifier` + `nuxtZodProviderId`.
 */
export interface NuxtZodTypeTemplateOptions {
  /** `zod/v3`, `zod/v4`, or `zod/mini` — must match Nitro virtual `#nuxt-zod/server`. */
  zodSpecifier: string
  zodVersion: 'v3' | 'v4' | 'mini'
  /**
   * When false, omit `H3Event.validate` — the Nitro plugin that installs it is not registered.
   * Derived from `nuxtZod.server !== false`.
   */
  serverEnabled: boolean
}

export function getNuxtZodTypeTemplateContents(options: NuxtZodTypeTemplateOptions): string {
  const { zodSpecifier, zodVersion, serverEnabled } = options
  const isMini = zodVersion === 'mini'
  const zImport = isMini
    ? `import type * as z from '${zodSpecifier}'`
    : `import type { z } from '${zodSpecifier}'`

  const zodConfigInputType = zodVersion === 'v3'
    ? `{
  customError?: (issue: import('zod/v3').ZodIssue) => string | undefined
}`
    : 'NonNullable<Parameters<typeof z.config>[0]>'

  const publicZodType = 'Omit<typeof z, \'config\'>'

  const nuxtZodImports = serverEnabled
    ? `import type {
  ZodErrorMessages,
  ValidationSchemaInput,
  ValidationOptions,
  InferValidated,
} from 'nuxt-zod'`
    : `import type {
  ZodErrorMessages,
} from 'nuxt-zod'`

  const h3Augment = serverEnabled
    ? `
declare module 'h3' {
  interface H3Event {
    validate: <T extends ValidationSchemaInput>(
      schema: T,
      options?: ValidationOptions,
    ) => Promise<InferValidated<T>>
  }
}
`
    : ''

  return `// Auto-generated by nuxt-zod
${zImport}
${nuxtZodImports}

type ZodConfigInput = ${zodConfigInputType}

declare module '#app' {
  interface NuxtApp {
    $zod: ${publicZodType}
    /**
     * Set by consumer plugins via \`provide: { zodConfig }\` (available after the plugin setup returns).
     * Not visible to \`useZod()\` in the same plugin body before return; use a separate plugin or Nitro \`registerInjectedZodConfig\`.
     */
    $zodConfig?: ZodConfigInput
  }
}

declare module 'vue' {
  interface ComponentCustomProperties {
    $zod: ${publicZodType}
  }
}

declare module '#nuxt-zod/server' {
  export const z: ${publicZodType}
  export const nuxtZodProviderId: '${zodVersion}'
  export function registerInjectedZodConfig(config: ZodConfigInput): void
  export type { ValidationSchema, ValidationSchemaInput, ValidationOptions, InferValidated, NuxtZodRuntimeValidation } from 'nuxt-zod'
}
${h3Augment}
declare module 'nuxt/schema' {
  interface AppConfigInput {
    zod?: {
      errors?: ZodErrorMessages
    }
  }
  interface AppConfig {
    zod?: {
      errors?: ZodErrorMessages
    }
  }
}

export {}
`
}
